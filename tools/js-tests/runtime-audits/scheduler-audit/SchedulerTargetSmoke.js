(function(){
    var checks=0;
    function expect(ok,message){++checks;if(!ok)throw Error('Scheduler target: '+message);}
    expect(typeof cc.Scheduler.prototype.scheduleUpdateForTarget==='function','missing scheduleUpdateForTarget');
    var scheduler=new cc.Scheduler(), order=[], first={update:function(dt){order.push('first');this.delta=dt;}},
        last={update:function(){order.push('last');}};
    scheduler.scheduleUpdateForTarget(last,10,false);
    scheduler.scheduleUpdateForTarget(first,-10,false);
    scheduler.update(0.25);
    expect(order.join(',')==='first,last','real update priority order');
    expect(first.delta===0.25,'update receiver/delta');
    scheduler.pauseTarget(first);order=[];scheduler.update(0.25);
    expect(scheduler.isTargetPaused(first),'pause state');
    expect(order.join(',')==='last','paused target excludes update');
    scheduler.resumeTarget(first);scheduler.setTimeScale(0.5);order=[];scheduler.update(0.25);
    expect(first.delta===0.125&&order.join(',')==='first,last','native time scale and resume');
    scheduler.unscheduleUpdateForTarget(last);scheduler.unscheduleUpdate(first);order=[];scheduler.update(0.25);
    expect(order.length===0,'both update cancellation names');
    scheduler.setTimeScale(1);
    var timer={calls:0,tick:function(){this.calls++;}};
    scheduler.schedule(timer.tick,timer,0,false,0,false,'finite');
    scheduler.update(0.1);scheduler.update(0.1);scheduler.update(0.1);
    expect(timer.calls===1,'false repeat converts to zero');
    scheduler.schedule('tick',timer,0,false,'named');
    scheduler.update(0.1);scheduler.update(0.1);
    expect(timer.calls===2,'selector and short overload');
    scheduler.unschedule('named',timer);scheduler.update(0.1);
    expect(timer.calls===2,'explicit timer key cancellation');
    scheduler.schedule(timer.tick,timer,0,true,'paused');scheduler.update(0.1);scheduler.update(0.1);
    expect(timer.calls===2,'short overload paused argument');
    scheduler.resumeTarget(timer);scheduler.update(0.1);scheduler.update(0.1);
    expect(timer.calls===3,'timer resumed');
    scheduler.unscheduleAllCallbacksForTarget(timer);scheduler.update(0.1);
    expect(timer.calls===3,'all callback cancellation');
    timer.__instanceId=731;
    scheduler.schedule(timer.tick,timer,0,false);scheduler.update(0.1);scheduler.update(0.1);
    scheduler.unschedule('731',timer);scheduler.update(0.1);
    expect(timer.calls===4,'legacy default key is stringified instance id');
    var keyed=0,keyedFn=function(){keyed++;};
    scheduler.scheduleCallbackForTarget(timer,keyedFn,0,cc.REPEAT_FOREVER,0,false);
    scheduler.update(0.1);scheduler.update(0.1);
    scheduler.unscheduleCallbackForTarget(timer,keyedFn);scheduler.update(0.1);
    expect(keyed===1,'deprecated callback identity cancellation');
    var rejected=false;try{scheduler.schedule(timer.tick,timer,1e300,false);}catch(error){rejected=true;}
    expect(rejected,'interval must fit native float');
    var firstCalls=0,nextCalls=0,changing={update:function(){firstCalls++;this.update=function(){nextCalls++;};
        scheduler.scheduleUpdateForTarget(this,-4,false);}};
    scheduler.scheduleUpdateForTarget(changing,-4,false);scheduler.update(0.1);scheduler.update(0.1);scheduler.update(0.1);
    expect(firstCalls===1&&nextCalls===2,'self-replacement retains new callback');
    scheduler.unscheduleAllForTarget(changing);
    var nodeCalls=0,ticks=0,Node=cc.Node.extend({update:function(){nodeCalls++;}}), node=new Node();
    node.setScheduler(scheduler);node.onEnter();
    scheduler.scheduleUpdateForTarget(node,0,false);
    scheduler.schedule(function(){ticks++;},node,0,false,'node');
    scheduler.update(0.1);scheduler.update(0.1);
    expect(nodeCalls===2&&ticks===1,'native Node target scheduled');
    node.pause();scheduler.update(0.1);
    expect(nodeCalls===2&&ticks===1,'Node.pause controls direct Scheduler entries');
    node.resume();scheduler.update(0.1);
    expect(nodeCalls===3&&ticks===2,'Node.resume controls direct Scheduler entries');
    node.cleanup();scheduler.update(0.1);
    expect(nodeCalls===3&&ticks===2,'Node.cleanup cancels direct Scheduler entries');
    node.onExit();
    var manager=new cc.ActionManager(), independent=new cc.Scheduler(), subject=new cc.Node();
    subject.setActionManager(manager);subject.setScheduler(independent);
    subject.onEnter();
    scheduler.scheduleUpdateForTarget(independent,0,false);
    independent.scheduleUpdateForTarget(manager,0,false);
    subject.runAction(cc.moveBy(1,cc.p(100,0)));
    independent.setTimeScale(0.5);
    scheduler.update(0.25);scheduler.update(0.25);scheduler.update(0.25);
    expect(Math.abs(subject.x-25)<0.01,'nested real Scheduler and ActionManager update');
    scheduler.unscheduleUpdate(independent);independent.unscheduleUpdate(manager);subject.stopAllActions();subject.onExit();
    var collected=0;
    (function(){var target={update:function(){collected++;}};scheduler.scheduleUpdateForTarget(target,0,false);})();
    jsb.garbageCollect();scheduler.update(0.1);
    expect(collected===1,'pure JS target survives GC while scheduled');
    scheduler.unscheduleAllCallbacks();scheduler.update(0.1);
    expect(collected===1,'all callbacks removed');
    var global=cc.director.getScheduler(), survivor={update:function(){}};
    global.scheduleUpdateForTarget(survivor,0,false);
    global.schedule(function(){},survivor,0,false,'stop');
    cc.log('SCHEDULER_TARGET_PASS '+checks+' checks');
})();
